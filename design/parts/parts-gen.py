# XOR, stage 1: (A OR B) AND NOT (A AND B), built only from switch-level parts.
#   AND section: relays A1, B1 in series from the + rail -> wire a1 (= A AND B) drives the coil of
#   NOT section: an NC relay; its contact is fed by
#   OR section: relays A2, B2 in parallel off the + rail -> wire o1 (= A OR B)
#   -> NC contact -> wire out -> lamp -> ground.  a1 hops over o1 at x=300.
# Hooks (Ken's app.js apply()): data-w on wires/pins/labels, data-energ on relays, data-lamp on the lamp,
# data-flow='out' on the conducting path. Net names: one, A, B, a1, o1, out (same as js/draw.js gate-XOR).
def xor_relay():
    def W(d,w,flow=False): return f"<path class='wire' data-w='{w}'{(' data-flow=\"out\"').replace(chr(34),chr(39)) if flow else ''} d='{d}'/>"
    def J(x,y,w): return f"<circle class='jdot' data-w='{w}' cx='{x}' cy='{y}' r='3.2'/>"
    def PIN(x,y,w): return f"<circle class='pin' data-w='{w}' cx='{x}' cy='{y}' r='4'/>"
    def T(x,y,t,w='',a='middle',cls='lbl'): return f"<text class='{cls}'{f' data-w={chr(39)}{w}{chr(39)}' if w else ''} x='{x}' y='{y}' text-anchor='{a}'>{t}</text>"
    def put(k,x,y,attrs=''): return P[k].replace('<svg ',f"<svg x='{x}' y='{y}' {attrs} ".rstrip()+' ',1)
    def group(x,y,w,h,label):
        tw=round(len(label)*8.2+16)      # tab sized for the part's larger 12px label (see .part-xor-relay in style.css)
        return (f"<rect class='group' x='{x}' y='{y}' width='{w}' height='{h}' rx='14'/>"
                f"<rect class='group-tab' x='{x+10}' y='{y-10}' width='{tw}' height='20' rx='9'/>"
                f"<text class='group-label' x='{x+10+tw/2}' y='{y+4}' text-anchor='middle'>{label}</text>")
    def relay(k,x,y,inp,cur):       # relay + coil input stub with pin/label + coil ground; cur = net that is live when current flows through the contact
        cx1,cx2,cy=x+14,x+46,y+60
        return (W(f'M{cx1} {cy} V{cy+20}',inp)+PIN(cx1,cy+24,inp)+T(cx1-10,cy+28,inp,inp,'end')+
                f"<path class='wire gnd' d='M{cx2} {cy} V{cy+10}'/>"+put('ground',cx2-30,cy+10)+
                put(k,x,y,f"data-energ='{inp}' data-w='{cur}'"))
    s =''
    s+=group(62,48,206,152,'A AND B')+group(62,206,150,262,'A OR B')+group(316,206,90,124,'NOT')+group(418,206,124,82,'A XOR B')
    # source: battery (+ left) top-left, its - side to ground
    s+=W('M40 80 H80','one')+W('M40 240 H80','one',True)+W('M40 370 H80','one',True)
    s+=J(40,80,'one')+J(40,240,'one')
    # AND: A1 -> B1 in series -> a1
    s+=W('M140 80 H190','A')      # between A1 and B1: live whenever A closes (same net name as js/draw.js)
    s+=W('M250 80 H300 V232 A8 8 0 0 1 300 248 V310 H344 V280','a1')   # a1 hops over o1 at (300,240)
    # OR: A2 || B2 -> o1 -> NC contact
    s+=W('M140 240 H292','o1',True)+W('M308 240 H330','o1',True)+W('M140 370 H170 V240','o1',True)+J(170,240,'o1')
    # NOT relay contact -> out -> lamp -> ground
    s+=W('M390 240 H430','out',True)+W('M490 240 H508 V250','out',True)+put('ground',478,250)
    s+=relay('relay-no',80,60,'A','A')+relay('relay-no',190,60,'B','a1')+relay('relay-no',80,220,'A','A')+relay('relay-no',80,350,'B','B')
    s+=f"<path class='wire gnd' d='M376 280 V290'/>"+put('ground',346,290)+put('relay-nc',330,220,"data-energ='a1' data-w='out'")
    s+=put('lamp',430,220,"data-lamp='out'")
    # signal names on the wires
    s+=T(276,72,'a1','a1')+T(232,232,'o1','o1')+T(410,232,'out','out')
    top=(W('M40 26 V406','one')+f"<path class='wire gnd' d='M100 26 H150 V36'/>"+put('ground',120,36)+put('battery',40,6)+
         T(70,58,'source','', 'middle'))
    s=top+"<g transform='translate(0 36)'>"+s+"</g>"
    return ("<svg class='part-group part-xor-relay' viewBox='0 0 548 516' width='548' height='516' fill='none' stroke-linecap='round' stroke-linejoin='round'>"
      "<!-- XOR, stage 1 = (A OR B) AND NOT (A AND B), relays only. viewBox 0 0 548 516. "
      "Pins: battery + (40,26) feeds the rail x=40; battery - (100,26) to ground. "
      "Inputs (coil pins): A at (94,180) [relay A1] and (94,340) [relay A2]; B at (204,180) [B1] and (94,470) [B2]. "
      "Internal nets: a1 = A AND B (B1 contact out, drives the NC coil at (344,316)); o1 = A OR B (joins at (170,276)); "
      "out = NC contact (390,276) -> lamp (430..490,276) -> ground (508,286). Everything below the battery sits in a translate(0 36) group. "
      "Hooks: data-w (wires, pins, labels; on a relay = its contact carries current), data-energ (relays), data-lamp (lamp), data-flow on the conducting path; net names one A B a1 o1 out. "
      "Without app.js: add on to every [data-w=n] whose net n is 1, energized to [data-energ=n], on to [data-lamp=out]. -->"
      +s+"</svg>")
P['xor-relay']=xor_relay()
for k in ['xor-relay']: open(O+k+'.svg','w').write(P[k].replace('<svg ',"<svg xmlns='http://www.w3.org/2000/svg' ",1))
